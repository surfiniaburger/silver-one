def _strip_markdown_fence(text: str) -> str:
    """Remove ```json ... ``` or ``` ... ``` fences."""
    text = text.strip()
    text = re.sub(r"^```(?:json)?\s*\n?", "", text)
    text = re.sub(r"\n?```\s*$", "", text)
    return text.strip()


def _extract_first_json_object(text: str) -> Optional[str]:
    """Find the first { ... } JSON object in text."""
    start = text.find("{")
    if start == -1:
        return None
    depth = 0
    for i, ch in enumerate(text[start:], start=start):
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                return text[start : i + 1]
    return None


def _escape_invalid_backslashes(text: str) -> str:
    """Escape lone backslashes that are not valid JSON escape sequences."""
    valid_escapes = set('"\\/ bfnrtu')
    result = []
    i = 0
    while i < len(text):
        if text[i] == "\\" and i + 1 < len(text):
            if text[i + 1] in valid_escapes:
                result.append(text[i])
                result.append(text[i + 1])
                i += 2
            else:
                result.append("\\\\")
                i += 1
        else:
            result.append(text[i])
            i += 1
    return "".join(result)


def _parse_llm_json(response_text: str) -> Optional[dict]:
    """
    Robustly parse a JSON object from an LLM response.
    Tries multiple candidates: raw, stripped fence, extracted object, escaped.
    Returns the parsed dict or None.
    """
    candidates = []
    raw = response_text.strip()
    if raw:
        candidates.append(raw)
    unfenced = _strip_markdown_fence(raw)
    if unfenced and unfenced not in candidates:
        candidates.append(unfenced)
    extracted = _extract_first_json_object(unfenced or raw)
    if extracted and extracted not in candidates:
        candidates.append(extracted)
        escaped = _escape_invalid_backslashes(extracted)
        if escaped not in candidates:
            candidates.append(escaped)

    for candidate in candidates:
        try:
            return json.loads(candidate)
        except Exception:
            continue
    return None


